#!/bin/bash

REPORT_FILE="hardware_inventory_$(date +%Y%m%d_%H%M%S).txt"

echo "Generating comprehensive hardware inventory report..."
echo "Report will be saved to: $REPORT_FILE"

{
    echo "================================================================================"
    echo "                        HARDWARE INVENTORY REPORT"
    echo "================================================================================"
    echo "Generated on: $(date)"
    echo "System: $(hostname)"
    echo "Generated by: $(whoami)"
    echo

    echo "================================================================================"
    echo "SYSTEM INFORMATION"
    echo "================================================================================"
    sudo dmidecode --type 1

    echo "================================================================================"
    echo "BIOS INFORMATION"
    echo "================================================================================"
    sudo dmidecode --type 0

    echo "================================================================================"
    echo "MOTHERBOARD INFORMATION"
    echo "================================================================================"
    sudo dmidecode --type 2

    echo "================================================================================"
    echo "PROCESSOR INFORMATION"
    echo "================================================================================"
    sudo dmidecode --type 4

    echo "================================================================================"
    echo "MEMORY INFORMATION"
    echo "================================================================================"
    sudo dmidecode --type 16,17

    echo "================================================================================"
    echo "SYSTEM SLOTS AND EXPANSION"
    echo "================================================================================"
    sudo dmidecode --type 9
} > "$REPORT_FILE"

echo "Hardware inventory report generated successfully: $REPORT_FILE"
